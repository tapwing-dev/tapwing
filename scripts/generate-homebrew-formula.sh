#!/usr/bin/env bash
# Generates the Homebrew formula (Formula/tapwing.rb) for a Tapwing release from
# the tarball checksums scripts/dist.sh writes.
#
#   scripts/generate-homebrew-formula.sh --version <VER> --dist-dir <DIR> [--repo <OWNER/REPO>] [--out <FILE>]
#
# --version   release version, with or without a leading v (e.g. 0.1.0)
# --dist-dir  directory with tapwing-<VER>-<target>.tar.gz.sha256 for
#             aarch64-apple-darwin, x86_64-apple-darwin and x86_64-unknown-linux-gnu
# --repo      GitHub repository the release is published in (default: tapwing-dev/tapwing)
# --out       file to write, or - for stdout (default: -)
#
# The URLs point at https://github.com/<repo>/releases/download/v<VER>/. A tarball
# next to its .sha256 is checked against it too. The formula installs bin/tapwing
# and share/tapwing/ (the bundled native-lane drivers, found through
# <prefix>/bin/../share/tapwing/drivers once Homebrew's symlinks are resolved).
set -euo pipefail

TARGETS=(aarch64-apple-darwin x86_64-apple-darwin x86_64-unknown-linux-gnu)

die() { echo "generate-homebrew-formula: $*" >&2; exit 1; }

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  else
    die "sha256sum or shasum is required"
  fi
}

version=""
dist_dir=""
repo="tapwing-dev/tapwing"
out="-"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --version) [[ $# -ge 2 ]] || die "--version needs a value"; version=$2; shift 2 ;;
    --dist-dir) [[ $# -ge 2 ]] || die "--dist-dir needs a value"; dist_dir=$2; shift 2 ;;
    --repo) [[ $# -ge 2 ]] || die "--repo needs a value"; repo=$2; shift 2 ;;
    --out) [[ $# -ge 2 ]] || die "--out needs a value"; out=$2; shift 2 ;;
    -h|--help) awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done

version=${version#v}
[[ -n "$version" ]] || die "--version is required"
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]] || die "--version $version is not a semver version"
[[ -n "$dist_dir" ]] || die "--dist-dir is required"
[[ -d "$dist_dir" ]] || die "--dist-dir $dist_dir is not a directory"
[[ "$repo" =~ ^[A-Za-z0-9._-]+/[A-Za-z0-9._-]+$ ]] || die "--repo $repo is not OWNER/REPO"

# Indexed like TARGETS (no associative arrays: macOS ships bash 3.2).
sha=()
for target in "${TARGETS[@]}"; do
  name="tapwing-$version-$target.tar.gz"
  sumfile="$dist_dir/$name.sha256"
  [[ -f "$sumfile" ]] || die "missing $sumfile (build it with scripts/dist.sh --target $target)"
  read -r hash file _ <"$sumfile" || true
  [[ "${hash:-}" =~ ^[0-9a-f]{64}$ ]] || die "$sumfile does not start with a 64-character lowercase hex SHA-256"
  [[ -z "${file:-}" || "${file#\*}" == "$name" ]] || die "$sumfile is for $file, not $name"
  if [[ -f "$dist_dir/$name" ]]; then
    got=$(sha256 "$dist_dir/$name")
    [[ "$got" == "$hash" ]] || die "$dist_dir/$name: SHA-256 $got, expected $hash (from $sumfile)"
  fi
  sha+=("$hash")
done

base="https://github.com/$repo/releases/download/v$version"

formula=$(cat <<EOF
# Generated by scripts/generate-homebrew-formula.sh for $repo v$version; do not edit by hand.
class Tapwing < Formula
  desc "Fast, black-box end-to-end testing for Flutter apps"
  homepage "https://github.com/$repo"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/tapwing-$version-aarch64-apple-darwin.tar.gz"
      sha256 "${sha[0]}"
    end
    on_intel do
      url "$base/tapwing-$version-x86_64-apple-darwin.tar.gz"
      sha256 "${sha[1]}"
    end
  end

  on_linux do
    on_intel do
      url "$base/tapwing-$version-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "${sha[2]}"
    end
  end

  def install
    bin.install "bin/tapwing"
    (share/"tapwing").install Dir["share/tapwing/*"]
  end

  test do
    out = shell_output("#{bin}/tapwing --version")
    assert_match "tapwing #{version}", out
    assert_match "tapwing android driver: #{version} (bundled)", out
    assert_match "tapwing ios driver: #{version} (bundled)", out if OS.mac?
  end
end
EOF
)

if [[ "$out" == "-" ]]; then
  printf '%s\n' "$formula"
else
  mkdir -p "$(dirname "$out")"
  printf '%s\n' "$formula" >"$out.tmp.$$"
  mv "$out.tmp.$$" "$out"
  echo "generate-homebrew-formula: wrote $out" >&2
fi
